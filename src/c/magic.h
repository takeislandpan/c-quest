/* === 第1章 詠唱の基本 === */
/* 呪文は printf("呪文名\n"); で唱える */
/* 1行で1回。上の行から順に1ターンずつ */

/* attack : 攻撃する（MP 2）           */
/* guard  : 身を守る。被ダメ半分（MP 1） */

/* === 第2章 ちからを 言葉にする（変数と型） === */
/* main の中、printf より前に 箱（変数）を書く */
/*   int  attack  = 10;   攻撃力              */
/*   int  defense = 10;   防御力              */
/*   int  hp      = 10;   体力                */
/*   char weapon  = 'S';  武器（1文字）        */
/* attack + defense + hp は SP まで（この面は 30） */
/* 1 SP で 1 上がる。こえると 魔力暴走        */

/* 武器（大文字1文字）                         */
/*   'S' 剣 : attack × 1.5          （MP 2）   */
/*   'B' 弓 : attack × 1.2          （MP 2）   */
/*   'M' 杖 : attack × 1.0 防御むし （MP 3）   */
/* ダメージ = 攻撃 − 相手の防御（さいていでも 1） */
/* 小数は 切り捨て。 10.5 なら 10              */
/* うける ダメージ = 相手の攻撃 − defense       */

/* 型（箱の 種類）                              */
/*   int    : 整数     10                      */
/*   double : 小数     10.5                    */
/*   char   : 1文字    'S'                     */
